-- A faithful-enough stand-in for a hosted Supabase project, so migrations can
-- be executed before they touch production.

create role anon nologin;
create role authenticated nologin;
create role service_role nologin bypassrls;

create schema extensions;
create schema auth;
create schema storage;

grant usage on schema public, storage to anon, authenticated;

-- ---- auth
create table auth.users (
  id uuid primary key default gen_random_uuid(),
  email text,
  email_confirmed_at timestamptz
);
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$$;
grant usage on schema auth to anon, authenticated;
grant execute on function auth.uid() to anon, authenticated;
-- Note: anon/authenticated get NO access to auth.users, as in Supabase.

-- ---- storage (helper bodies match Supabase's own)
create table storage.buckets (
  id text primary key, name text, public boolean default false,
  file_size_limit bigint, allowed_mime_types text[]
);
create table storage.objects (
  id uuid primary key default gen_random_uuid(),
  bucket_id text references storage.buckets(id),
  name text,
  owner uuid,
  created_at timestamptz default now()
);
alter table storage.objects enable row level security;
grant all on storage.objects to anon, authenticated;
grant select on storage.buckets to anon, authenticated;

create function storage.foldername(name text) returns text[] language plpgsql immutable as $$
declare _parts text[];
begin
  select string_to_array(name, '/') into _parts;
  return _parts[1:array_length(_parts,1)-1];
end $$;
create function storage.extension(name text) returns text language plpgsql immutable as $$
declare _parts text[]; _filename text;
begin
  select string_to_array(name, '/') into _parts;
  select _parts[array_length(_parts,1)] into _filename;
  return reverse(split_part(reverse(_filename), '.', 1));
end $$;
grant execute on function storage.foldername(text), storage.extension(text) to anon, authenticated;

-- ---- Supabase's permissive defaults: RLS, not grants, is the real guard
alter default privileges in schema public grant all on tables to anon, authenticated;
alter default privileges in schema public grant all on sequences to anon, authenticated;
alter default privileges in schema public grant execute on functions to anon, authenticated;

-- ---- the three production tables as they existed before any migration
create table public.event_registrations (
  id uuid primary key default gen_random_uuid(),
  name text, email text, phone text, school text, event text,
  created_at timestamptz default now(),
  payment boolean
);
create table public.workshop_bookings (
  id bigint generated by default as identity primary key,
  school_name text, contact_no text, school_email text,
  created_at timestamptz default now(),
  completed boolean, agreed boolean, paid boolean
);
create table public.join_us_submissions (
  id uuid primary key default gen_random_uuid(),
  name text, email text, phone text, school text, youtube_link text,
  created_at timestamptz default now(),
  completed boolean, agreed boolean, paid boolean
);
grant all on public.event_registrations, public.workshop_bookings, public.join_us_submissions to anon, authenticated;

